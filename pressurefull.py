mult = 3000

a0 = 1.55

b_0 = (
    510.594*a0
    + ((11.9192*mult)**2)/(87.8169*mult)
    - ((11.9192)**2)/(87.8169)
)

vecP = np.array([

    # a+, T+, b+
    0.00000,
    0.00000,
    0.00000,

    # a-, T-, b-
    1.55369491e+00,
    510.594,
    b_0,

    # c
    0.00000,

    # k
    87.8169*mult,

    # lambda+
    0.00000,

    # lambda-
    -11.9192*mult,

    # d+
    0.00000,

    # d-
    5.32663570e+03,

    # kp
    2*(87.8169*mult/144)

])

paramsP, couplingsP = functions.GenParams(
    vecP,
    model="2t66p"
)

mapa = []

temperaturas = np.linspace(0,1500,40)
presiones = np.linspace(0,10,40)

for T in temperaturas:

    print("Temperatura =", T)

    for P in presiones:

        variables = np.array([
            1,
            1,
            T,
            0.1,
            P
        ])

        prov = functions.MinimizeEnergy(
            paramsP,
            variables,
            couplingsP,
            mask=np.array([1,1,0,1,0]),
            verbose=False,
            cycles=120,
            delta=1e-6
        )

        qp = abs(prov[1][0])
        qm = abs(prov[1][1])

        tol = 1e-3

        if qp < tol and qm < tol:
            fase = 0

        elif qp > tol and qm < tol:
            fase = 1

        elif qp < tol and qm > tol:
            fase = 2

        else:
            fase = 3

        mapa.append([T,P,fase])

mapa = np.array(mapa)

