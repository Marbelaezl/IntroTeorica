import numpy as np
import functions
# PARTE 1: SIMULACION ORIGINAL
vec = ([-1, 1, 0.3, -1.5, 5, 0.6, -0.2, 0.25, 0.1, -0.2])

results = [[0,0,0,0]]
status = [0]

params, couplings = functions.GenParams(vec)

index = 0

print("====================================")
print("SIMULACION TEMPERATURA")
print("====================================")

for i in np.linspace(0,15,10):

    print("T =", i)

    variables = np.array([
        np.max([np.random.rand()*100, results[index][0]]),
        np.max([np.random.rand()*100, results[index][1]]),
        i,
        np.max([np.random.rand()*100, results[index][3]])
    ])

    prov = functions.MinimizeEnergy(
        params,
        variables,
        couplings,
        mask=np.array([1,1,0,1]),
        verbose=False,
        cycles=120,
        delta=1e-16
    )

    results.append(prov[1])
    status.append(prov[0])

    index += 1

results_np = np.array(results)
status_np = np.array(status).reshape(-1,1)

energy_np = np.zeros((len(results_np),1))

for i in range(len(results_np)):

    energy_np[i] = functions.FreeEnergy(
        params,
        results_np[i],
        couplings
    )

datos_totales = np.hstack([
    results_np,
    status_np,
    energy_np
])

np.savetxt(
    "datos_simulacion.txt",
    datos_totales,
    fmt='%2.8f'
)

print("datos_simulacion.txt generado")

